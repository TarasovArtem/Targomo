// --- S8: malformed JSON + valid report (captured from oracle commit) --
// Protects: the malformed file is skipped (never thrown), the valid file
// is still processed, and the warning's stable, project-owned portion -
// built via path.join("reports","cypress",filename), so the assertion
// expresses that join call rather than hardcoding an OS-specific
// separator (preserving Windows/Linux equivalence).
//
// RUNTIME_VOLATILE_WARNING_PROJECTION: the tail of this warning
// (`err.message` from JSON.parse's own SyntaxError) is generated by the
// V8 engine, not by this project's code, and its exact English wording
// is not a guaranteed-stable API - it has changed across V8/Node
// versions historically, and this repository's own CI (.github/workflows,
// node-version: 22) already runs a different Node version than the one
// this golden was authored against. Freezing that exact string forever
// would make the #19.7 regression barrier fail on a future Node upgrade
// for a reason that has nothing to do with Cypress-adapter extraction
// correctness - the actual #19.6/#19.7 contract is "the malformed file
// produces a warning naming itself and is skipped", not "V8 phrases JSON
// syntax errors exactly this way". The stable, project-owned prefix
// (built from this project's own literal "reports"/"cypress" path
// segments and filename) IS still frozen exactly; only the engine-
// generated diagnostic tail is excluded from the frozen surface.
function projectMalformedWarningPrefix(warningText, expectedPrefix) {
  return warningText.startsWith(expectedPrefix) && warningText.length > expectedPrefix.length;
}

test("S8 malformed JSON + valid report: current adapter matches the historical oracle - malformed skipped, valid processed, warning ordering preserved", () => {
  const reportsDir = tmpReportsDir();
  try {
    writeReport(reportsDir, "valid.json", {
      stats: { tests: 1, passes: 0, failures: 1, pending: 0, duration: 1 },
      results: [{ file: "/cypress/e2e/tests/s8_valid.cy.js", suites: [{ title: "S8", suites: [], tests: [{ title: "fails", state: "failed", err: { message: "m8" } }] }] }],
    });
    fs.writeFileSync(path.join(reportsDir, "broken.json"), "{ not valid json");

    const result = cypressAdapter.collect({ reportsDir });

    assert.deepStrictEqual(
      { testResults: result.testResults, failedTests: result.failedTests },
      {
        testResults: {
          found: true,
          totals: { tests: 1, passed: 0, failed: 1, pending: 0, duration: 1 },
          specs: [{ specFile: "cypress/e2e/tests/s8_valid.cy.js", tests: 1, passed: 0, failed: 1, pending: 0, duration: 1 }],
        },
        failedTests: [
          { title: "fails", fullTitle: null, suite: "S8", specFile: "cypress/e2e/tests/s8_valid.cy.js", status: "failed", duration: null, error: { message: "m8", stack: null }, screenshot: null },
        ],
      }
    );

    // Warnings: stable project-owned prefix frozen exactly; V8's own
    // JSON.parse diagnostic tail deliberately excluded (see
    // RUNTIME_VOLATILE_WARNING_PROJECTION comment above). Still proves
    // exactly one warning, naming exactly the malformed file's relative
    // path, with genuine error detail attached (never an empty tail).
    const expectedPrefix = `Could not parse ${path.join("reports", "cypress", "broken.json")}: `;
    assert.equal(result.warnings.length, 1);
    assert.ok(
      projectMalformedWarningPrefix(result.warnings[0], expectedPrefix),
      `warning should start with "${expectedPrefix}" and include non-empty detail; got: ${result.warnings[0]}`
    );
  } finally {
    fs.rmSync(reportsDir, { recursive: true, force: true });
  }
});

