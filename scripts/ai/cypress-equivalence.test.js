const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const cypressAdapter = require("./adapters/cypress-adapter");

const HISTORICAL_ORACLE_COMMIT = "1aff8f69484b7df5a293e7f1761f580fa2d3c9b0";
const ROOT = path.resolve(__dirname, "..", "..");

function tmpReportsDir() {
  return fs.mkdtempSync(path.join(os.tmpdir(), "cypress-equivalence-reports-"));
}

function writeReport(dir, filename, reportObject) {
  fs.writeFileSync(path.join(dir, filename), JSON.stringify(reportObject));
}

// --- S1: mixed result set (captured from oracle commit HISTORICAL_ORACLE_COMMIT) --
// Protects: totals aggregation, failedTests extraction (only the failed
// test, never the passed/pending ones), and screenshot resolution, all
// together in one representative "normal" run.

test("S1 mixed result: current adapter matches the historical oracle for pass+fail+pending+screenshot", (t) => {
  const reportsDir = tmpReportsDir();
  // Screenshot resolution is only proven ROOT-relative (matching real
  // production behavior) when screenshotsDir is the real
  // cypress/screenshots directory - an overridden temp directory would
  // leak an absolute machine-specific path into the result, since
  // normalizeSpecPath only strips a path that starts with this
  // collector's own ROOT (see context-utils.js). This mirrors the
  // pre-existing resolveScreenshotPath tests in cypress-adapter.test.js
  // that also use the real path for the same reason.
  //
  // Cleanup is deliberately scoped to ONLY this test's own uniquely-named
  // "s1_mixed.cy.js" subdirectory, never the shared cypress/screenshots
  // ROOT itself - cypress-adapter.test.js's own pre-existing screenshot
  // tests (and S5 below) also read/write under that same shared root
  // concurrently (Node's test runner runs separate test files as
  // concurrent processes by default), so a whole-root rmSync here could
  // delete another file's in-flight fixture out from under it. Since
  // resolveScreenshotPath()/collect() only ever touch
  // <screenshotsDir>/<basename(specFile)>/, deleting just that one
  // basename subdirectory is sufficient and never collides with any
  // other test's differently-named subdirectory.
  const specDir = path.join(ROOT, "cypress", "screenshots", "s1_mixed.cy.js");
  t.after(() => {
    fs.rmSync(reportsDir, { recursive: true, force: true });
    fs.rmSync(specDir, { recursive: true, force: true });
  });
  try {
    writeReport(reportsDir, "report.json", {
      stats: { tests: 3, passes: 1, failures: 1, pending: 1, duration: 42 },
      results: [
        {
          file: "/cypress/e2e/tests/s1_mixed.cy.js",
          suites: [
            {
              title: "S1 Suite",
              suites: [],
              tests: [
                { title: "passes fine", state: "passed" },
                { title: "is pending", state: "pending" },
                {
                  title: "fails here",
                  state: "failed",
                  duration: 12,
                  err: { message: "AssertionError: boom", estack: "AssertionError: boom\n  at x" },
                },
              ],
            },
          ],
        },
      ],
    });
    fs.mkdirSync(specDir, { recursive: true });
    fs.writeFileSync(path.join(specDir, "S1 Suite -- fails here (failed).png"), "");

    const result = cypressAdapter.collect({ reportsDir });

    // Historical golden (oracle: HISTORICAL_ORACLE_COMMIT).
    assert.deepStrictEqual(result, {
      testResults: {
        found: true,
        totals: { tests: 3, passed: 1, failed: 1, pending: 1, duration: 42 },
        specs: [{ specFile: "cypress/e2e/tests/s1_mixed.cy.js", tests: 3, passed: 1, failed: 1, pending: 1, duration: 42 }],
      },
      failedTests: [
        {
          title: "fails here",
          fullTitle: null,
          suite: "S1 Suite",
          specFile: "cypress/e2e/tests/s1_mixed.cy.js",
          status: "failed",
          duration: 12,
          error: { message: "AssertionError: boom", stack: "AssertionError: boom\n  at x" },
          screenshot: path.posix.join("cypress/screenshots/s1_mixed.cy.js", "S1 Suite -- fails here (failed).png"),
        },
      ],
      warnings: [],
    });
  } finally {
    fs.rmSync(reportsDir, { recursive: true, force: true });
  }
});

