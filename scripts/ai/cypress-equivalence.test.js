// --- S5: screenshot matrix (captured from oracle commit) --------------
// Protects: missing directory -> null, directory-exists-but-no-match ->
// null, single exact match, highest-numbered retry attempt selected,
// loose-prefix decoys rejected, and special regex characters in the test
// title handled safely (escaped, not interpreted as regex syntax).

test("S5 screenshot matrix: current adapter matches the historical oracle across matching/missing/retry/decoy cases", () => {
  const specFile = "/cypress/e2e/tests/s5_screens.cy.js";
  const suiteTitles = ["S5 Suite"];

  const cases = [
    { label: "no directory", title: "no dir test", screenshots: null, expected: null },
    { label: "no match", title: "no match test", screenshots: { "S5 Suite -- no match test.png": "" }, expected: null },
    {
      label: "single match",
      title: "single test",
      screenshots: { "S5 Suite -- single test (failed).png": "" },
      expected: "cypress/screenshots/s5_screens.cy.js/S5 Suite -- single test (failed).png",
    },
    {
      label: "multiple attempts - highest wins",
      title: "retry test",
      screenshots: { "S5 Suite -- retry test (failed) (1).png": "", "S5 Suite -- retry test (failed) (2).png": "" },
      expected: "cypress/screenshots/s5_screens.cy.js/S5 Suite -- retry test (failed) (2).png",
    },
    {
      label: "loose-prefix decoy rejected",
      title: "prefix test",
      screenshots: { "S5 Suite -- prefix test extra (failed).png": "" },
      expected: null,
    },
    {
      label: "special regex characters in title",
      title: "weird (title) [x]",
      screenshots: { "S5 Suite -- weird (title) [x] (failed).png": "" },
      expected: "cypress/screenshots/s5_screens.cy.js/S5 Suite -- weird (title) [x] (failed).png",
    },
  ];

  // Uses the real cypress/screenshots directory (not an overridden temp
  // dir) for the same ROOT-relative-path reason as S1 above - cleaned up
  // after every case so no residue remains between cases or after the
  // test. Cleanup is scoped to only this test's own "s5_screens.cy.js"
  // subdirectory, never the shared cypress/screenshots root itself - see
  // S1's comment above for why a whole-root deletion here would be
  // unsafe to run concurrently with other test files/cases that share
  // that same root.
  const specDir = path.join(ROOT, "cypress", "screenshots", "s5_screens.cy.js");
  for (const c of cases) {
    try {
      if (c.screenshots) {
        fs.mkdirSync(specDir, { recursive: true });
        for (const [name] of Object.entries(c.screenshots)) fs.writeFileSync(path.join(specDir, name), "");
      }
      const result = cypressAdapter.resolveScreenshotPath(specFile, suiteTitles, c.title);
      assert.equal(result, c.expected, c.label);
    } finally {
      fs.rmSync(specDir, { recursive: true, force: true });
    }
  }
});

